export const SPECIALIST_UNITS: Unit[] = specs.map(
  ([faction, id, name, kind, level, gold, stats, portrait, role]) => {
    const [attack, defense, hp, range, speed, morale] = stats,
      siege = kind === 'Siège';
    return {
      id,
      name,
      kind,
      ...(kind === 'Cavalerie'
        ? {
            mount: 'Cheval' as const,
            cavalryWeight: (id === 'haven_riders' ? 'Lourde' : 'Légère') as 'Lourde' | 'Légère',
          }
        : {}),
      factions: [faction],
      race: ['bluedwarves', 'khazad'].includes(faction)
        ? 'Nain'
        : ['edhellond', 'lindon', 'eregion', 'imladris', 'elves', 'woodland'].includes(faction)
          ? 'Elfe'
          : faction === 'mordor'
            ? 'Orque'
            : 'Homme',
      attack,
      defense,
      hp,
      range,
      speed,
      morale,
      level,
      slots: siege ? 8 : kind === 'Élite' ? 3 : kind === 'Cavalerie' ? 2 : 1,
      cost: {
        gold,
        wood: siege ? Math.ceil(gold * 0.6) : kind === 'Archers' ? Math.ceil(gold * 0.25) : 0,
        stone: 0,
        iron: Math.ceil(gold * (kind === 'Élite' ? 0.5 : 0.3)),
        food: Math.ceil(gold * 0.4),
      },
      upkeep: { gold: Math.round(gold * 0.7) / 100, food: Math.round(gold * 1.2) / 100 },
      portrait,
      trait: role + ' Formation et statistiques propres à la campagne.',
      signature: true,
    };
  },
);
